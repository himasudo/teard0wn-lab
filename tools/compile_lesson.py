#!/usr/bin/env python3
"""Compile each C lesson in lessons/compiled/ and generate src/compiled.js.

For every lesson it compiles with gcc -O0 -g, links at a fixed base so
intra-module calls are relocated, and extracts:

  - the .text + .rodata image (hex), loaded at 0x1000 = the engine's CODE base,
  - per-instruction address, bytes, and Intel-syntax disassembly (objdump),
  - the C source line each instruction belongs to (addr2line / DWARF).

The engine runs these bytes directly; the site shows the C source and the
disassembly side by side and highlights both from RIP. Run this when a lesson's
C changes. The committed src/compiled.js is what the site loads; a separate test
(tests/compiled_lessons.test.js) runs each lesson in the engine and checks its
result, so correctness does not depend on reproducing exact bytes in CI.
"""
import json, re, subprocess, pathlib, tempfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / 'lessons' / 'compiled'
BASE = 0x1000
FLAGS = ['-O0', '-g3', '-gdwarf-4', '-fno-asynchronous-unwind-tables',
         '-fcf-protection=none', '-fno-stack-protector']
INSN = re.compile(r'^\s*([0-9a-f]+):\s+((?:[0-9a-f]{2} )+)\s+(.*\S)\s*$')

def run(cmd):
    return subprocess.run(cmd, check=True, capture_output=True, text=True).stdout

def build(lesson, d):
    c = SRC / lesson['file']
    obj, elf, binf = d/'l.o', d/'l.elf', d/'l.bin'
    run(['gcc', *FLAGS, '-c', str(c), '-o', str(obj)])
    run(['ld', str(obj), f'-Ttext={BASE:#x}', '-e', lesson['entry'], '-o', str(elf)])
    run(['objcopy', '-O', 'binary', '-j', '.text', '-j', '.rodata', str(elf), str(binf)])
    code = binf.read_bytes()
    entry = None
    for line in run(['nm', str(elf)]).splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[2] == lesson['entry']:
            entry = int(parts[0], 16)
    if entry is None:
        raise SystemExit(f"entry {lesson['entry']} not found in {lesson['file']}")
    # instructions
    insns, addrs = [], []
    for line in run(['objdump', '-d', '-Mintel', str(elf)]).splitlines():
        m = INSN.match(line)
        if not m:
            continue
        addr = int(m.group(1), 16)
        insns.append({'addr': addr,
                      'bytes': m.group(2).strip(),
                      'text': re.sub(r'\s+', ' ', m.group(3)).strip()})
        addrs.append(hex(addr))
    # C line per instruction
    out = run(['addr2line', '-e', str(elf), *addrs]).splitlines()
    for ins, loc in zip(insns, out):
        mm = re.search(r':(\d+)', loc)
        ins['line'] = int(mm.group(1)) if mm and mm.group(1) != '0' else None
    return {
        'id': lesson['id'], 'title': lesson['title'], 'subtitle': lesson['subtitle'],
        'track': lesson['track'], 'inputLabel': lesson['inputLabel'],
        'input': lesson['input'], 'expect': lesson['expect'], 'retBits': lesson['retBits'],
        'intro': lesson['intro'],
        'source': c.read_text().rstrip('\n').split('\n'),
        'base': BASE, 'entry': entry,
        'codeHex': code.hex(), 'insns': insns,
    }

def main():
    lessons = json.loads((SRC / 'index.json').read_text())
    out = []
    with tempfile.TemporaryDirectory(prefix='teard0wn-lesson-') as tmp:
        d = pathlib.Path(tmp)
        for lesson in lessons:
            out.append(build(lesson, d))
    banner = '// Generated by tools/compile_lesson.py from lessons/compiled/. Do not edit by hand.\n'
    body = 'export const compiledLessons = ' + json.dumps(out, separators=(',', ':')) + ';\n'
    (ROOT / 'src' / 'compiled.js').write_text(banner + body)
    print(f'Wrote src/compiled.js: {len(out)} lessons, '
          f'{sum(len(l["insns"]) for l in out)} instructions.')

if __name__ == '__main__':
    main()
