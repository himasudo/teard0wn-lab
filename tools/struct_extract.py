#!/usr/bin/env python3
"""Compile each struct example in lessons/types/ at -O2 and extract the
base-relative field accesses (offset + width) the code makes through the struct
pointer in rdi. Emits src/typedata.js: the observed access trace per example,
plus the original C source for the reveal. The structure-recovery view infers
the layout from the trace; the source is only shown after."""
import json, re, subprocess, pathlib, tempfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRCDIR = ROOT / 'lessons' / 'types'
FLAGS = ['-O2', '-fno-asynchronous-unwind-tables', '-fcf-protection=none', '-fno-stack-protector']
SIZE = {'BYTE': 1, 'WORD': 2, 'DWORD': 4, 'QWORD': 8}
ACC = re.compile(r'\b(BYTE|WORD|DWORD|QWORD) PTR \[rdi(?:\+0x([0-9a-f]+))?\]', re.I)


def run(c):
    return subprocess.run(c, check=True, capture_output=True, text=True).stdout


def accesses(cfile, fn, d):
    obj = d / 'o.o'
    run(['gcc', *FLAGS, '-c', str(cfile), '-o', str(obj)])
    text = run(['objdump', '-d', '-Mintel', str(obj)])
    best = {}
    for kw, off in ACC.findall(text):
        o = int(off, 16) if off else 0
        s = SIZE[kw.upper()]
        best[o] = max(best.get(o, 0), s)   # widest access at each offset wins
    return [{'off': o, 'size': best[o]} for o in sorted(best)]


def main():
    with tempfile.TemporaryDirectory(prefix='teard0wn-struct-') as tmp:
        d = pathlib.Path(tmp)
        out = []
        for p in json.loads((SRCDIR / 'index.json').read_text()):
            cfile = SRCDIR / f"{p['id']}.c"
            out.append({'id': p['id'], 'title': p['title'], 'note': p['note'],
                        'csource': cfile.read_text().strip(),
                        'accesses': accesses(cfile, p['fn'], d)})
        banner = '// Generated by tools/struct_extract.py from lessons/types/. Do not edit by hand.\n'
        (ROOT / 'src' / 'typedata.js').write_text(banner + 'export const typeExamples = ' + json.dumps(out, separators=(',', ':')) + ';\n')
        print(f'Wrote src/typedata.js: {len(out)} examples.')
        for e in out:
            print(' ', e['id'], e['accesses'])


if __name__ == '__main__':
    main()
