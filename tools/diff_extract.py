#!/usr/bin/env python3
"""Compile each vulnerable/patched pair in lessons/diff/ and generate
src/diffpairs.js for the binary-diffing view.

For each pair it compiles <id>-vuln.c and <id>-fix.c with gcc -O0 and extracts
the per-instruction address, bytes, and Intel-syntax disassembly of the named
function from each. The site diffs the two disassemblies so the security fix
shows up as added/changed instructions. No execution is involved, so only the
listings are emitted. Run this when a pair's C changes; the committed
src/diffpairs.js is what the site loads.
"""
import json, re, subprocess, pathlib, tempfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRCDIR = ROOT / 'lessons' / 'diff'
BASE = 0x1000
FLAGS = ['-O0', '-fno-asynchronous-unwind-tables', '-fcf-protection=none', '-fno-stack-protector']
INSN = re.compile(r'^\s*([0-9a-f]+):\s+((?:[0-9a-f]{2} )+)\s+(.*\S)\s*$')


def run(cmd):
    return subprocess.run(cmd, check=True, capture_output=True, text=True).stdout


def disasm(cfile, fn, d):
    obj, elf = d / 'p.o', d / 'p.elf'
    run(['gcc', *FLAGS, '-c', str(cfile), '-o', str(obj)])
    run(['ld', str(obj), f'-Ttext={BASE:#x}', '-e', fn, '-o', str(elf)])
    insns = []
    for line in run(['objdump', '-d', '-Mintel', str(elf)]).splitlines():
        m = INSN.match(line)
        if not m:
            continue
        insns.append({'addr': int(m.group(1), 16),
                      'bytes': m.group(2).strip(),
                      'text': re.sub(r'\s+', ' ', m.group(3)).strip()})
    return insns


def main():
    with tempfile.TemporaryDirectory(prefix='teard0wn-diff-') as tmp:
        d = pathlib.Path(tmp)
        out = []
        for p in json.loads((SRCDIR / 'index.json').read_text()):
            a = disasm(SRCDIR / f"{p['id']}-vuln.c", p['fn'], d)
            b = disasm(SRCDIR / f"{p['id']}-fix.c", p['fn'], d)
            out.append({'id': p['id'], 'title': p['title'], 'note': p['note'],
                        'a': {'label': p['label_a'], 'insns': a},
                        'b': {'label': p['label_b'], 'insns': b}})
        banner = '// Generated by tools/diff_extract.py from lessons/diff/. Do not edit by hand.\n'
        body = 'export const diffPairs = ' + json.dumps(out, separators=(',', ':')) + ';\n'
        (ROOT / 'src' / 'diffpairs.js').write_text(banner + body)
        print(f'Wrote src/diffpairs.js: {len(out)} pairs, '
              f'{sum(len(p["a"]["insns"]) + len(p["b"]["insns"]) for p in out)} instructions.')


if __name__ == '__main__':
    main()
