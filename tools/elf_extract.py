#!/usr/bin/env python3
"""Compile a small dynamically-linked program and extract the real ELF
structure the linking/loading walkthrough explains, into src/elfdata.js.

Everything shown in the lab comes from an actual gcc build on this machine:
the ELF header, the segments the loader maps, the sections the linker uses,
the two call styles (a resolved intra-module call vs a call through the PLT),
the PLT stub that jumps through the GOT, and the JUMP_SLOT relocation the
dynamic linker applies. Run this to refresh src/elfdata.js. A test checks the
invariant that ties it together (the PLT jump targets the relocated GOT slot),
so correctness does not depend on reproducing exact addresses in CI.
"""
import json, re, subprocess, pathlib, tempfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
SAMPLE = '''#include <stdio.h>
int add(int a, int b) { return a + b; }
int main(void) {
    printf("%d\\n", add(2, 3));
    return 0;
}
'''

def run(cmd, **kw):
    return subprocess.run(cmd, check=True, capture_output=True, text=True, **kw).stdout

def main():
    with tempfile.TemporaryDirectory(prefix='teard0wn-elf-') as tmp:
        d = pathlib.Path(tmp)
        (d/'s.c').write_text(SAMPLE)
        run(['gcc','-O0','s.c','-o','elf'], cwd=d)
        run(['gcc','-O0','-c','s.c','-o','s.o'], cwd=d)
        elf, obj = str(d/'elf'), str(d/'s.o')

        H = run(['readelf','-h',elf])
        def hf(label): return re.search(rf'{label}:\s*(.+)', H).group(1).strip()
        header = {'class': hf('Class'), 'type': hf('Type'), 'machine': hf('Machine'),
                  'entry': hf('Entry point address')}

        interp = re.search(r'(/\S+)', run(['readelf','-p','.interp',elf])).group(1)

        segs = []
        for m in re.finditer(r'^\s*(INTERP|LOAD|DYNAMIC|GNU_RELRO|NOTE|GNU_STACK|PHDR)\s+0x\w+\s+0x(\w+)\s+0x\w+\s+0x(\w+)\s+0x(\w+)\s+([RWE ]{1,3}?)\s+0x\w+\s*$',
                             run(['readelf','-lW',elf]), re.M):
            segs.append({'type': m.group(1), 'vaddr': '0x'+m.group(2).lstrip('0').rjust(1,'0'),
                         'filesz': '0x'+m.group(3), 'flags': m.group(5).strip()})

        keep = {'.interp','.dynsym','.rela.dyn','.rela.plt','.plt.sec','.plt','.got','.got.plt','.text','.rodata','.data','.bss'}
        sections = []
        for m in re.finditer(r'^\s*\[\s*\d+\]\s+(\.\S+)\s+(\w+)\s+0*(\w+?)\s', run(['readelf','-SW',elf]), re.M):
            if m.group(1) in keep:
                sections.append({'name': m.group(1), 'type': m.group(2), 'addr': '0x'+(m.group(3) or '0')})

        dis = run(['objdump','-d','-Mintel',elf])
        main_body = re.search(r'<main>:\n(.*?)\n\n', dis, re.S).group(1)
        def call_line(pat):
            m = re.search(rf'^\s*(\w+):\t([0-9a-f ]+?)\s*\tcall\s+\w+ <({pat}[^>]*)>', main_body, re.M)
            return {'site': '0x'+m.group(1), 'bytes': m.group(2).strip(), 'target': m.group(3)}
        calls = {'direct': call_line('add'), 'plt': call_line('printf')}

        plt_block = re.search(r'<printf@plt>:\n(.*?)\n\n', dis, re.S).group(1)
        plt_insns = [{'bytes': b.strip(), 'text': re.sub(r'\s+',' ',t).strip()}
                     for a,b,t in re.findall(r'^\s*(\w+):\t([0-9a-f ]+?)\s*\t([^\n#]+)', plt_block, re.M)]
        got_target = '0x'+re.search(r'#\s*(\w+)\s+<printf', plt_block).group(1)

        rp = re.search(r'^0*(\w+)\s+\w+\s+(R_X86_64_\w+)\s+\w+\s+(\S+)', run(['readelf','-rW',elf]), re.M)
        # restrict to the .rela.plt (printf) entry
        rp = re.search(r'^0*(\w+)\s+\w+\s+(R_X86_64_JUMP_SLOT)\s+\w+\s+(printf\S*)', run(['readelf','-rW',elf]), re.M)
        reloc = {'offset': '0x'+rp.group(1), 'type': rp.group(2), 'symbol': rp.group(3)}

        # In the .o the intra-module call is the first call in main, still a zeroed
        # placeholder (objdump shows it as <main+..> because it is unrelocated).
        obj_main = re.search(r'<main>:\n(.*?)(?:\n\n|\Z)', run(['objdump','-d','-Mintel',obj]), re.S).group(1)
        obj_call = re.search(r'\t([0-9a-f ]+?)\s*\tcall\s', obj_main)
        reloc_story = {'obj': obj_call.group(1).strip(), 'linked': calls['direct']['bytes'],
                       'target': calls['direct']['target']}

    data = {'source': SAMPLE.rstrip('\n').split('\n'), 'header': header, 'interp': interp,
            'segments': segs, 'sections': sections, 'calls': calls,
            'pltStub': {'addr': calls['plt']['target'] and ('0x'+re.search(r'(\w+) <printf@plt',dis).group(1)),
                        'insns': plt_insns, 'gotTarget': got_target},
            'reloc': reloc, 'relocStory': reloc_story}
    banner = '// Generated by tools/elf_extract.py from a real gcc build. Do not edit by hand.\n'
    (ROOT/'src'/'elfdata.js').write_text(banner + 'export const elf = ' + json.dumps(data, separators=(',',':')) + ';\n')
    print(f"Wrote src/elfdata.js: {len(segs)} segments, {len(sections)} sections, "
          f"PLT->{got_target}, reloc {reloc['offset']} {reloc['type']}")

if __name__ == '__main__':
    main()
